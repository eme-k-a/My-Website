// JSON-LD Person (ARCHITECTURE §11.3; R9, WP-31). A pure function of the content and the build
// date, rendered into the head of `/` and `/resume/` at prerender time (never shipped as code).
// `jobTitle` and `worksFor` appear only while a work entry `isCurrent`, so they drop out on the
// first build after the co-op ends (the weekly rebuild, WP-36, refreshes it). Email and telephone
// are left out on purpose: the email to keep it from scrapers, and the phone exists nowhere.
import { isCurrent } from '../content/format';
import { displayName } from '../content/selectors';
import type { Content } from '../content/types';

/** The headshot the Person points at (public/images/, regenerated by `npm run media`). */
export const HEADSHOT_PATH = '/images/headshot-800.jpg';

export interface PersonJsonLd {
  '@context': 'https://schema.org';
  '@type': 'Person';
  name: string;
  alternateName: string;
  url: string;
  image: string;
  jobTitle?: string;
  worksFor?: { '@type': 'Organization'; name: string };
  alumniOf: { '@type': 'CollegeOrUniversity'; name: string };
  address: {
    '@type': 'PostalAddress';
    addressLocality: string;
    addressRegion?: string;
    addressCountry: 'CA';
  };
  sameAs: string[];
  knowsAbout: string[];
}

/** "St. John's, NL" -> locality "St. John's", region "NL" (the last comma splits them). */
function splitLocation(location: string): { locality: string; region?: string } {
  const at = location.lastIndexOf(',');
  if (at < 0) return { locality: location.trim() };
  return { locality: location.slice(0, at).trim(), region: location.slice(at + 1).trim() };
}

/** The Person object for the build date `now`. */
export function personJsonLd(c: Content, now: Date): PersonJsonLd {
  const site = c.meta.siteUrl;
  const edu = c.education[0];
  if (!edu) throw new Error('Content has no education entry');
  const current = c.experiences.find((w) => isCurrent(w, now));
  const { locality, region } = splitLocation(c.contact.location);
  const knowsAbout = [...new Set(c.skills.flatMap((line) => line.items))];
  return {
    '@context': 'https://schema.org',
    '@type': 'Person',
    name: c.contact.name,
    alternateName: displayName(c),
    url: `${site}/`,
    image: `${site}${HEADSHOT_PATH}`,
    ...(current
      ? {
          jobTitle: current.role,
          worksFor: { '@type': 'Organization' as const, name: current.org },
        }
      : {}),
    alumniOf: { '@type': 'CollegeOrUniversity', name: edu.institution },
    address: {
      '@type': 'PostalAddress',
      addressLocality: locality,
      ...(region ? { addressRegion: region } : {}),
      addressCountry: 'CA',
    },
    sameAs: [c.contact.linkedin, ...(c.contact.github ? [c.contact.github] : [])],
    knowsAbout,
  };
}

/**
 * The `<script type="application/ld+json">` data block. `<` is escaped as `<` so no string in
 * the content can close the element; the block is data, so the CSP needs no hash for it.
 */
export function jsonLdTag(c: Content, now: Date): string {
  const json = JSON.stringify(personJsonLd(c, now)).replace(/</g, '\\u003c');
  return `<script type="application/ld+json">${json}</script>`;
}
